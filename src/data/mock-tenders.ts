function daysFromNow(days: number): Timestamp {
  const date = new Date();
  date.setDate(date.getDate() + days);
  return Timestamp.fromDate(date);
}

function daysAgo(days: number): Timestamp {
  const date = new Date();
  date.setDate(date.getDate() - days);
  return Timestamp.fromDate(date);
}

